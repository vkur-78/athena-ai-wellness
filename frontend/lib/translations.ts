export function formatRelativeDateLabel(
  dateInput: Date | string,
  lang: WebsiteLanguage,
  todayStr?: string
): string {
  const d = typeof dateInput === "string" ? new Date(dateInput) : dateInput;
  if (isNaN(d.getTime())) return "";

  const now = new Date();
  const diffMs = now.getTime() - d.getTime();
  const diffHours = Math.floor(diffMs / (1000 * 60 * 60));
  const diffDays = Math.floor(diffMs / (1000 * 60 * 60 * 24));

  if (diffHours < 1) {
    if (lang === "hi") return "अभी-अभी";
    if (lang === "ta") return "சற்றுமுன்";
    if (lang === "te") return "ఇప్పుడే";
    if (lang === "mr") return "आत्ताच";
    if (lang === "gu") return "હમણાં જ";
    return "Just now";
  }

  if (diffHours < 24) {
    if (lang === "hi") return `${diffHours} घंटे पहले`;
    if (lang === "ta") return `${diffHours} மணிநேரம் முன்`;
    if (lang === "te") return `${diffHours} గంటల క్రితం`;
    if (lang === "mr") return `${diffHours} तासांपूर्वी`;
    if (lang === "gu") return `${diffHours} કલાક પહેલાં`;
    return `${diffHours} ${diffHours === 1 ? "hour" : "hours"} ago`;
  }

  if (diffDays === 1) {
    if (lang === "hi") return "कल";
    if (lang === "ta") return "நேற்று";
    if (lang === "te") return "నిన్న";
    if (lang === "mr") return "काल";
    if (lang === "gu") return "ગઈકાલે";
    return "Yesterday";
  }

  if (diffDays < 7) {
    if (lang === "hi") return "इस सप्ताह";
    if (lang === "ta") return "இந்த வாரம்";
    if (lang === "te") return "ఈ వారం";
    if (lang === "mr") return "या आठवड्यात";
    if (lang === "gu") return "આ અઠવાડિયે";
    return "This week";
  }

  if (lang === "hi") return "पहले";
  if (lang === "ta") return "முன்பு";
  if (lang === "te") return "గతంలో";
  if (lang === "mr") return "पूर्वी";
  if (lang === "gu") return "અગાઉ";
  return "Earlier";
}
